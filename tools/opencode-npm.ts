// Generate modules/patches/npm/opencode.scm from opencode's bun.lock and a log
// of the tarball paths `bun install' requested.
//
// Usage: bun tools/opencode-npm.ts BUN_LOCK REQUEST_LOG VERSION > opencode.scm
//
// REQUEST_LOG holds one "GET /path" line per request, as written by
// tools/opencode-registry-recorder.ts.  Every path must belong to a package in
// the lockfile; its sha512 integrity becomes the origin's hash, so Guix checks
// each tarball against the very hash Bun checks it against.

const [lockPath, logPath, version] = process.argv.slice(2)
if (!lockPath || !logPath || !version) {
  console.error("usage: opencode-npm.ts BUN_LOCK REQUEST_LOG VERSION")
  process.exit(2)
}

type Entry = { url: string; integrity: string; fileName?: string }

const lock = Bun.JSONC.parse(await Bun.file(lockPath).text()) as {
  workspaces: Record<string, Record<string, Record<string, string>>>
  packages: Record<string, unknown[]>
}

// Full commit hashes of github: dependencies, as written in the workspaces'
// package.json; the package entries only carry an abbreviation.
const githubSpecs = new Set<string>()
for (const workspace of Object.values(lock.workspaces))
  for (const field of Object.values(workspace))
    if (field && typeof field === "object")
      for (const spec of Object.values(field))
        if (typeof spec === "string" && spec.startsWith("github:")) githubSpecs.add(spec.slice("github:".length))

const byPath = new Map<string, Entry>()
for (const value of Object.values(lock.packages)) {
  const id = value[0] as string
  const github = id.match(/^(.+)@github:([^/]+)\/([^#]+)#(.+)$/)
  if (github) {
    const [, name, owner, repo, short] = github
    const full = [...githubSpecs].find((spec) => spec.startsWith(`${owner}/${repo}#${short}`))?.split("#")[1]
    if (!full) throw new Error(`no full commit for ${id}`)
    byPath.set(`/repos/${owner}/${repo}/tarball/${short}`, {
      url: `https://codeload.github.com/${owner}/${repo}/legacy.tar.gz/${full}`,
      integrity: value[3] as string,
      fileName: `${name}-${short}.tar.gz`,
    })
    continue
  }
  if (id.includes("@workspace:")) continue
  if (typeof value[1] !== "string" || value[1] !== "") throw new Error(`unsupported lockfile entry: ${id}`)
  const at = id.lastIndexOf("@")
  const name = id.slice(0, at)
  const pkgVersion = id.slice(at + 1)
  const base = name.split("/").pop()
  const path = `/${name}/-/${base}-${pkgVersion}.tgz`
  byPath.set(path, { url: `https://registry.npmjs.org${path}`, integrity: value[3] as string })
}

const requested = new Set(
  (await Bun.file(logPath).text())
    .replaceAll("\0", "")
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.startsWith("GET "))
    .map((line) => decodeURIComponent(line.slice(4))),
)

const lines: string[] = []
for (const path of [...requested].sort()) {
  const entry = byPath.get(path)
  if (!entry) throw new Error(`requested path not in bun.lock: ${path}`)
  if (!entry.integrity?.startsWith("sha512-")) throw new Error(`no sha512 integrity for ${path}`)
  const hash = entry.integrity.slice("sha512-".length)
  if (entry.fileName) lines.push(`   (github ${q(path)} ${q(entry.url)} ${q(entry.fileName)}\n           ${q(hash)})`)
  else lines.push(`   (npm ${q(path)}\n        ${q(hash)})`)
}

function q(s: string) {
  if (/["\\]/.test(s)) throw new Error(`unexpected character in ${s}`)
  return `"${s}"`
}

process.stdout.write(`;;; -*- mode: scheme; -*-
;;;
;;; npm dependency origins for opencode.
;;;
;;; Generated by tools/update-opencode-npm.sh from bun.lock of opencode
;;; v${version}; do not edit by hand.  Each element is (PATH . ORIGIN): PATH is
;;; the URL path \`bun install' requests from its registry (or, for the one
;;; github: dependency, from GITHUB_API_URL), and ORIGIN is that tarball.  The
;;; hashes are the lockfile's own sha512 integrity values.
;;;
;;; ${requested.size} tarballs: what \`bun install --frozen-lockfile' fetches for
;;; packages/cli and packages/app on x86_64-linux.

(define-module (patches npm opencode)
  #:use-module (guix base64)
  #:use-module (guix download)
  #:use-module (guix packages)
  #:export (%opencode-npm-sources))

(define (npm path integrity)
  (cons path
        (origin
          (method url-fetch)
          (uri (string-append "https://registry.npmjs.org" path))
          (hash (content-hash (base64-decode integrity) sha512)))))

(define (github path url file-name integrity)
  (cons path
        (origin
          (method url-fetch)
          (uri url)
          (file-name file-name)
          (hash (content-hash (base64-decode integrity) sha512)))))

(define %opencode-npm-sources
  (list
${lines.join("\n")}))
`)
